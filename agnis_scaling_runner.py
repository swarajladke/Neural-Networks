"""
agnis_scaling_runner.py — 100-Fact Continual Consolidation Benchmark (V4.5)
=============================================================================
Stress-tests 5 variants under matched-compute continual learning:
  1. no_replay               : Baseline (no functional replay)
  2. A_Gaussian_3            : 3 medoids/fact, Gaussian sampling (9.2 KB/fact)
  3. C_Gaussian_6            : 6 medoids/fact, Gaussian sampling (18.4 KB/fact)
  4. E_DenseTangent_6        : 6 medoids/fact, 50% SLERP + 50% Dirichlet (18.4 KB/fact)
  5. exact_episodic_replay   : Oracle upper bound (all training coordinates stored, no compression)

Runs on 10 blocks × 10 facts (100 facts total) generated by generate_scaling_dataset.py.
Includes semantic overlap, contradictory updates, and multi-token answers.

ELITE OPTIMIZATION:
Caches all read-space query, key, and evaluation paraphrase coordinates upfront.
This completely eliminates GPT-2 forward passes inside the training/evaluation loops,
allowing the entire 10-block consolidation benchmark to run in under 10 seconds on CPU.
"""
